def build_cfg(spec):
    loader = copy.deepcopy(spec["loader"])
    # FP16模式，不使用量化
    loader["torch_dtype"] = "float16"
    
    cfg = {
        "model_name": spec["model_name"],
        "model_id": spec["model_id"],
        "local_path": None,
        "source": spec["source"],
        "modelscope_id": spec["modelscope_id"],
        "modelscope_cache_dir": os.path.join(PROJECT_ROOT, "models"),
        "loader": loader,
        "deployment": spec["deployment"],  # 添加部署配置
        "inference": {
            "max_new_tokens": 32,
            "do_sample": False,
            "system_prompt": (
                "You are a helpful assistant. Answer with only the choice letter (A/B/C/D/E/F)\n"
                "for multiple choice questions, or only 'Yes'/'No' for binary questions.\n"
                "Do not explain. One character only."
            ),
        },
        "eriq": {
            "supported_modalities": ["single_image", "multi_image", "interleaved"],
            "answer_extraction_mode": "first_letter",
        },
    }
    return cfg


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    run_list = []

    for spec in MODEL_SPECS_FP16_20B:
        out_name = f"{spec['series']}-{spec['size']}-fp16-20b.yaml"
        out_path = os.path.join(OUT_DIR, out_name)
        cfg = build_cfg(spec)
        with open(out_path, "w", encoding="utf-8") as f:
            yaml.safe_dump(cfg, f, allow_unicode=False, sort_keys=False)

        run_list.append(
            {
                "config": out_path,
                "series": spec["series"],
                "size": spec["size"],
                "quant": "fp16",
                "param_count": spec["param_count"],
                "deployment": spec["deployment"],
                "env": spec["env"],
                "run_enabled": spec["run_enabled"],
                "skip_reason": spec["skip_reason"],
                "output_name": f"{spec['series']}-{spec['size']}-fp16-20b_smoke20.json",
            }
        )

    run_list_path = os.path.join(OUT_DIR, "run_list_minimal_fp16_20b.yaml")
    with open(run_list_path, "w", encoding="utf-8") as f:
        yaml.safe_dump({"runs": run_list}, f, allow_unicode=False, sort_keys=False)

    print(f"[OK] FP16-20B 配置目录: {OUT_DIR}")
    print(f"[OK] FP16-20B run list: {run_list_path}")
    print(f"[OK] 共生�?{len(run_list)} �?FP16-20B 配置")


if __name__ == "__main__":
    main()
